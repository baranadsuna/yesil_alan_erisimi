def tr(key: str, lang: str | None = None, *args, **kwargs) -> str:
    """Retrieve translated string with optional positional or keyword formatting."""
    lang_code = lang if (lang and lang in STRINGS) else DEFAULT_LANGUAGE
    val = STRINGS.get(lang_code, {}).get(key)
    if val is None:
        val = STRINGS[DEFAULT_LANGUAGE].get(key, key)
    if args or kwargs:
        try:
            if args:
                return val.format(*args, **kwargs)
            return val.format(*kwargs.values(), **kwargs)
        except Exception:
            try:
                return val % (args if args else kwargs)
            except Exception:
                return val
    return val
